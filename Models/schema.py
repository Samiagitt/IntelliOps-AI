
from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add


class AgentSchema(BaseModel):

    messages: Annotated[list, add] = Field(...,description="List of messages processed by the agent")

    user_question: str = Field(...,description="Original question asked by the user")

    curated_question: str = Field(...,description="Curated user question")

    prompt_query: str = Field(...,description="Prompt containing SQL database context")

    generated_SQL_Query: str = Field(...,description="SQL query generated by the agent")

    is_safe: Literal["Yes", "No"] = Field(...,description="Whether the SQL query is safe to execute")

    comments: str = Field(...,description="Comments from the SQL safety judge")

    result: str = Field(...,description="SQL query execution result")

    final_response: str = Field(...,description="Final answer generated by the agent")


class JudgeSchema(BaseModel):

    answer: Literal["Yes", "No"] = Field(...,description="Whether the SQL query is safe")

    comments: str = Field(...,description="Feedback from the SQL safety judge")

    
