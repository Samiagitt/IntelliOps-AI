from pydantic import BaseModel, Field
from typing import Annotated,Literal
from operator import add

class AgentSchema(BaseModel):
    messages: Annotated[list,add]=Field(..., description="List of messages to be processed by the agent")
    user_question: str=Field(..., description="The original question asked by the user")
    curated_question: str= Field(...,description="curated user question")
    prompt_query: str=Field(..., description="A detailed prompt with SQL DB context that will help agent to generate SQL query") 
    is_safe: Literal["yes","No"]=Field(...,description="Indicates whether the generated SQL query is safe to execute or not ")
    generated_SQL_Query:str=Field(..., description="SQL query generated by the agent based on the curated question and prompt context") 
    result: str=Field(..., description="The result of executing the generated SQL quesry on the database") 
    final_response:str=Field(..., description="The final answer generated by the agent based on the SQL query execution result and the curated question")